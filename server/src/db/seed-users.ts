import { randomBytes } from "node:crypto";
import type { Database } from "./pool.ts";
import { MAX_PASSWORD_LENGTH, MIN_PASSWORD_LENGTH, hashPassword } from "../http/passwords.ts";

/**
 * The accounts a fresh deployment gets, and the only code that writes them.
 *
 * ## Nothing here ever updates an account
 *
 * Seeding is `INSERT ... ON CONFLICT (id) DO NOTHING` on purpose. The tempting version —
 * upsert, so a changed `DEFAULT_USERS` "takes effect" — turns every restart into a
 * credential reset for accounts people are already using, and it does so silently: the
 * operator sees a 200 in their logs and the user sees a login that stopped working. An
 * account that exists is an account somebody owns; this module never touches its password
 * or its display name, and a new `DEFAULT_USERS` value simply has nothing left to do.
 *
 * ## Why a bad value stops the boot instead of seeding the good half
 *
 * `parseDefaultUsers` throws, and `main.ts` lets it throw. A deployment that seeds `alice`
 * and silently skips `bob` looks healthy and is missing an account nobody can create
 * without a session — so a typo in `DEFAULT_USERS` is a startup failure with the offending
 * entry named in it, which is a message the operator can act on.
 */

/**
 * Ids that can be an account.
 *
 * The same rule `users.id` enforces in the database (the CHECK in
 * `migrations/006_users_and_sessions.sql`) and `CHAT_USERS` enforces in the environment,
 * copied here because both account entry points of this feature — this module and the
 * creation route — have to enforce exactly one rule, and a `db/` module is not going to
 * import the API layer to find it.
 */
export const USER_ID_PATTERN = /^[A-Za-z0-9._@-]{1,64}$/;

/** The accounts every fresh deployment starts with. */
export const DEFAULT_USER_IDS = ["alice", "bob"] as const;

/** Bytes behind a generated password: 12 bytes is 16 base64url characters. */
const GENERATED_PASSWORD_BYTES = 12;

export interface DefaultUser {
  id: string;
  password: string;
}

/**
 * Read `DEFAULT_USERS` as `id:password,id:password`.
 *
 * The entry is trimmed and split on its FIRST `:` only, so a password may itself contain
 * colons; blank entries are skipped, which makes a trailing comma harmless. Both halves
 * are trimmed as well, so a password cannot begin or end with whitespace — one that needs
 * to can be generated by the server instead.
 *
 * An empty or absent value is not an error: it means "no passwords were supplied", and
 * every default account then gets a generated one. That differs from `CHAT_USERS`, where
 * an empty roster cannot serve its purpose at all.
 *
 * An unusable entry throws, naming the entry verbatim: this runs at startup, so the
 * failure has to tell the operator which part of their value to fix.
 */
export function parseDefaultUsers(raw: string | undefined): DefaultUser[] {
  if (!raw?.trim()) return [];

  const users: DefaultUser[] = [];
  const seen = new Set<string>();

  for (const entry of raw.split(",")) {
    const trimmed = entry.trim();
    if (!trimmed) continue;

    const separator = trimmed.indexOf(":");
    if (separator === -1) {
      throw new Error(`DEFAULT_USERS entry "${trimmed}" must be id:password`);
    }
    const id = trimmed.slice(0, separator).trim();
    const password = trimmed.slice(separator + 1).trim();

    if (!USER_ID_PATTERN.test(id)) {
      throw new Error(
        `DEFAULT_USERS entry "${trimmed}" has an id that must match [A-Za-z0-9._@-] and be at most 64 characters`,
      );
    }
    if (password.length < MIN_PASSWORD_LENGTH || password.length > MAX_PASSWORD_LENGTH) {
      throw new Error(
        `DEFAULT_USERS entry "${trimmed}" has a password that must be between ` +
          `${MIN_PASSWORD_LENGTH} and ${MAX_PASSWORD_LENGTH} characters`,
      );
    }
    if (seen.has(id)) {
      throw new Error(`DEFAULT_USERS declares "${id}" twice (entry "${trimmed}")`);
    }
    seen.add(id);
    users.push({ id, password });
  }

  return users;
}

/**
 * Create the default accounts that do not exist yet.
 *
 * A password comes from `raw` when `DEFAULT_USERS` names that account, and is otherwise
 * generated and logged — the log is the operator's ONLY copy of a generated password, so
 * a caller without a `log` is throwing it away. The line is emitted only after the
 * transaction commits, so a seed that rolled back cannot print a password that was never
 * stored, and an account that already existed produces no line at all (which is also why
 * a later boot never repeats a generated password).
 *
 * All inserts share one transaction: either every missing account is created or none is,
 * and a failure halfway leaves no half-seeded deployment behind. The response says which
 * ids were actually created, in `DEFAULT_USER_IDS` order, so a caller can tell a first
 * boot from every boot after it without reading the database.
 *
 * An entry naming any other account is not seeded — the two defaults are fixed — and is
 * reported in one log line, because a configuration value that silently does nothing is
 * the kind of thing an operator only discovers when an account is missing. Never updates
 * an existing account: see the note at the top of this module.
 */
export async function seedDefaultUsers(
  db: Database,
  options: { raw?: string | undefined; log?: ((line: string) => void) | undefined } = {},
): Promise<{ created: string[] }> {
  const supplied = parseDefaultUsers(options.raw);
  const log = options.log ?? (() => {});

  const suppliedById = new Map(supplied.map((user) => [user.id, user.password]));
  const plans = DEFAULT_USER_IDS.map((id) => {
    const suppliedPassword = suppliedById.get(id);
    return suppliedPassword === undefined
      ? { id, password: randomBytes(GENERATED_PASSWORD_BYTES).toString("base64url"), generated: true }
      : { id, password: suppliedPassword, generated: false };
  });

  const defaultIds: readonly string[] = DEFAULT_USER_IDS;
  for (const user of supplied) {
    if (defaultIds.includes(user.id)) continue;
    log(
      `DEFAULT_USERS entry for "${user.id}" ignored: only ${DEFAULT_USER_IDS.join(" and ")} are seeded`,
    );
  }

  // Hashed before the transaction opens: scrypt is deliberately slow, and holding a
  // connection while two hashes run buys nothing a caller can observe.
  const prepared: Array<{ id: string; password: string; generated: boolean; hash: string }> = [];
  for (const plan of plans) {
    prepared.push({ ...plan, hash: await hashPassword(plan.password) });
  }

  const created = await db.transaction(async (tx) => {
    const inserted: string[] = [];
    for (const account of prepared) {
      const rows = await tx.query<{ id: string }>(
        `INSERT INTO users (id, display_name, password_hash)
         VALUES ($1, $2, $3)
         ON CONFLICT (id) DO NOTHING
         RETURNING id`,
        [account.id, account.id, account.hash],
      );
      for (const row of rows) inserted.push(row.id);
    }
    return inserted;
  });

  for (const id of created) {
    const account = prepared.find((candidate) => candidate.id === id);
    if (!account) continue;
    log(
      account.generated
        ? `default user "${id}" created with a generated password — this is the only copy, ` +
            `save it now: password="${account.password}"`
        : `default user "${id}" created from DEFAULT_USERS`,
    );
  }

  return { created };
}
